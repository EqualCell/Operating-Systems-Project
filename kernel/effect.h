#ifndef _KERNEL_EFFECT_H_
#define _KERNEL_EFFECT_H_

#include "types.h"

typedef int int32;

#define EFFECT_ABI_VERSION      1U

/* Operations */
#define EFFECT_OP_APPEND        1U
#define EFFECT_OP_CREATE        2U

/* Hard bounds (sized to fit safely within xv6 30-block log reservation) */
#define EFFECT_MAX_PATH         128U
#define EFFECT_MAX_PAYLOAD      512U

/* Symbolic status and outcome codes */
#define EFFECT_OK_COMMITTED     0    /* New execution committed & durable */
#define EFFECT_OK_CACHED        1    /* Retry matched committed record; no re-exec */
#define EFFECT_ERR_INVALID      (-1) /* Malformed args, bad version, or bounds */
#define EFFECT_ERR_REVOKED      (-2) /* Grant was explicitly revoked */
#define EFFECT_ERR_CONSUMED     (-3) /* Grant already spent by a different req_id */
#define EFFECT_ERR_STALE        (-4) /* Target file version or generation mismatch */
#define EFFECT_ERR_ARG_MISMATCH (-5) /* Retry key/req_id matched, but payload/op/path differed */
#define EFFECT_ERR_TABLE_FULL   (-6) /* Persistent effect/grant table has no free slots */
#define EFFECT_ERR_NOT_RECORDED (-7) /* Query found no record (not proof of non-execution) */
#define EFFECT_ERR_PERM         (-8) /* Caller lacks controller/agent authority or raw write blocked */
#define EFFECT_ERR_NOENT        (-9) /* Target file or grant does not exist */
#define EFFECT_ERR_EXIST        (-10)/* File already exists on CREATE */
#define EFFECT_ERR_NOSPC        (-11)/* Disk or inode allocation failed */
#define EFFECT_ERR_IO           (-12)/* Underlying storage/transaction failure */

/* Grant lifecycle states */
#define GRANT_STATE_UNUSED      0U
#define GRANT_STATE_ACTIVE      1U
#define GRANT_STATE_CONSUMED    2U
#define GRANT_STATE_REVOKED     3U

/* Process authorization roles */
#define ROLE_NORMAL             0U
#define ROLE_CONTROLLER         1U   /* Trusted host/controller utility: may issue/revoke grants */
#define ROLE_AGENT              2U   /* Untrusted agent worker: sticky across fork/exec, raw writes blocked */

/* Crash injection hook stages (Person 4 specification) */
#define CRASH_HOOK_NONE                 0
#define CRASH_HOOK_LOG_WRITE_COUNT      1 /* Crash on N-th log_write() registration */
#define CRASH_HOOK_BEFORE_COMMIT_HDR    2 /* Inside commit(), after write_log(), before write_head() */
#define CRASH_HOOK_AFTER_COMMIT_HDR     3 /* Inside commit(), after write_head(), before install_trans() */
#define CRASH_HOOK_AFTER_INSTALL        4 /* Inside commit(), after install_trans(), before clearing lh.n */
#define CRASH_HOOK_AFTER_GRANT_CONSUME  5 /* Inside sys_effect_checked, after state update, before end_op() */

/*
 * Extended checked effect request structure (688 bytes, 8-byte aligned).
 * Passed via pointer to sys_effect_checked().
 */
struct effect_checked_req {
  uint32 abi_version;                  /* Offset 0:   Must be EFFECT_ABI_VERSION */
  uint32 op;                           /* Offset 4:   EFFECT_OP_APPEND (CREATE deferred in ext) */
  uint64 grant_id;                     /* Offset 8:   64-bit capability ID issued by controller */
  uint64 req_id;                       /* Offset 16:  64-bit idempotency key generated by client */
  uint64 arg_hash;                     /* Offset 24:  FNV-1a 64-bit hash of (op, path, payload[0..n-1]) */
  uint32 payload_len;                  /* Offset 32:  0 <= payload_len <= EFFECT_MAX_PAYLOAD */
  uint32 flags;                        /* Offset 36:  Reserved (must be 0) */
  char   path[EFFECT_MAX_PATH];        /* Offset 40:  NUL-terminated target path (128 bytes) */
  uint8  payload[EFFECT_MAX_PAYLOAD];  /* Offset 168: Raw bounded bytes to append (512 bytes) */
  int32  out_status;                   /* Offset 680: Kernel writes symbolic EFFECT_* status here */
  int32  out_bytes;                    /* Offset 684: Kernel writes bytes written or cached result */
};

/*
 * Trusted-controller grant creation specification (168 bytes, 8-byte aligned).
 * Passed via pointer to sys_grant_create().
 */
struct grant_spec {
  uint32 abi_version;                  /* Offset 0:   Must be EFFECT_ABI_VERSION */
  uint32 allowed_op;                   /* Offset 4:   EFFECT_OP_APPEND */
  uint32 max_payload_len;              /* Offset 8:   Max bytes permitted <= EFFECT_MAX_PAYLOAD */
  uint32 flags;                        /* Offset 12:  Reserved (must be 0) */
  char   path[EFFECT_MAX_PATH];        /* Offset 16:  Target path to snapshot & bind (128 bytes) */
  uint64 out_grant_id;                 /* Offset 144: Kernel writes newly allocated grant_id */
  uint32 out_inum;                     /* Offset 152: Snapshot bound inode number */
  uint32 out_gen;                      /* Offset 156: Snapshot bound allocation generation */
  uint64 out_version;                  /* Offset 160: Snapshot bound file data version */
};

/*
 * Status query and response structures (32 bytes each, 8-byte aligned).
 * Passed via pointers to sys_effect_status().
 */
struct effect_status_query {
  uint32 abi_version;                  /* Offset 0:  Must be EFFECT_ABI_VERSION */
  uint32 is_extended;                  /* Offset 4:  0 = base key lookup, 1 = (grant_id, req_id) */
  uint64 key_or_req_id;                /* Offset 8:  64-bit base key or extended req_id */
  uint64 grant_id;                     /* Offset 16: 0 for base, or target grant_id */
  uint64 expected_arg_hash;            /* Offset 24: 0 to skip check, or FNV-1a hash to verify */
};

struct effect_status_result {
  int32  status;                       /* Offset 0:  EFFECT_OK_COMMITTED, EFFECT_ERR_REVOKED, etc. */
  int32  bytes_written;                /* Offset 4:  Historical result value */
  uint32 grant_state;                  /* Offset 8:  Current GRANT_STATE_* if is_extended == 1 */
  uint32 reserved;                     /* Offset 12: Padding */
  uint64 committed_version;            /* Offset 16: File version produced by this effect */
  uint64 recorded_arg_hash;            /* Offset 24: Stored argument fingerprint */
};

/* Compile-time ABI layout checks */
typedef char assert_effect_req_size[(sizeof(struct effect_checked_req) == 688) ? 1 : -1];
typedef char assert_grant_spec_size[(sizeof(struct grant_spec) == 168) ? 1 : -1];
typedef char assert_status_q_size[(sizeof(struct effect_status_query) == 32) ? 1 : -1];
typedef char assert_status_r_size[(sizeof(struct effect_status_result) == 32) ? 1 : -1];

#endif /* _KERNEL_EFFECT_H_ */