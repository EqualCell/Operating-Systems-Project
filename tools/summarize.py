#!/usr/bin/env python3
"""Turn evidence/<run>/results.json into docs/test-results.md (so the doc cannot drift from the evidence).
usage: python3 tools/summarize.py [evidence/final] [docs/test-results.md]"""
import json
import os
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "evidence/final"
dst = sys.argv[2] if len(sys.argv) > 2 else "docs/test-results.md"
doc = json.load(open(os.path.join(src, "results.json")))
env, res, summ = doc["environment"], doc["results"], doc["summary"]
by = {r["id"]: r for r in res}

L = ["# Test results (generated by tools/summarize.py from `%s/results.json`)" % src, "",
     f"**PASS {summ['PASS']}  FAIL {summ['FAIL']}  ERROR {summ['ERROR']}**  — {len(res)} cases, "
     f"{sum(len(r['checks']) for r in res)} individual checks, {doc.get('total_seconds')} s wall-clock.", "",
     "## Environment (recorded automatically)", ""]
for k, v in env.items():
    if k == "source_sha256":
        continue
    L.append(f"* **{k}**: `{v}`")
L += ["", "## All cases", "", "| ID | group | what it proves | result | checks | boots | s |", "|---|---|---|---|---|---|---|"]
for r in res:
    ok = sum(c["pass_"] for c in r["checks"])
    L.append(f"| {r['id']} | {r['group']} | {r['title']} | **{r['result']}** | {ok}/{len(r['checks'])} | {len(r['boots'])} | {r['seconds']} |")

L += ["", "## Crash/replay sweeps — one row per crash point", ""]
for cid in ("C1", "C2", "C3", "C4", "C5"):
    r = by.get(cid)
    if not r:
        continue
    p = r["params"]
    L += [f"### {cid}: {r['title']}", "",
          f"scenario `{p.get('scenario')}`, op `{p.get('op')}`, path `{p.get('path')}`, payload `{p.get('payload')}`, key `{p.get('key')}`, "
          f"CPUs {p.get('cpus')}, **K = {p.get('log_write_calls_K')} log_write calls, L = {p.get('logged_blocks_L')} logged blocks, "
          f"{p.get('disk_writes_per_effect')} disk writes per effect**", ""]
    for t in r["tables"]:
        L += ["| crash point | crashed | log.n on dead disk | effect on disk after log replay | key on disk after log replay | blocks recovered at boot | 1st replay | 2nd replay | final: once? | verdict |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for row in t["rows"]:
            L.append(f"| `{row['arm']}` | {row['crashed']} | {row['log_n']} | {row['view_effect']} | {row['view_key']} | {row['recovered_blocks']} | "
                     f"{row['replay1']} | {row['replay2']} | {row['final_file_ok_once']} | {'PASS' if row['verdict'] == 'PASS' else row['verdict'][:60]} |")
        L.append("")

for cid, head in (("E1", "Cost per effect"), ("E2", "Recovery cost")):
    r = by.get(cid)
    if r:
        L += [f"## {head} ({cid})", ""]
        for t in r["tables"]:
            cols = list(t["rows"][0].keys())
            L += [f"**{t['name']}**", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            L += ["| " + " | ".join(str(x.get(c, "")) for c in cols) + " |" for x in t["rows"]]
            L.append("")
        for n in r["notes"]:
            L.append(f"> {n}")
        L.append("")

L += ["## Mutation tests: the suite must FAIL on broken kernels", "", "| mutant | caught by | result on broken kernel | failed checks |", "|---|---|---|---|"]
for r in res:
    if r["group"] == "mutation":
        for t in r["tables"]:
            for row in t["rows"]:
                L.append(f"| {r['id'][2:]} | {row['test']} | {row['result']} | {row['failed_checks']} (first: {row['first_failed'][:60]}) |")

L += ["", "## Per-case checks (expected vs observed)", ""]
for r in res:
    L += [f"### {r['id']} — {r['title']} — {r['result']}", ""]
    L += [f"> {n}" for n in r["notes"]]
    L += ["", "| check | expected | observed | ok |", "|---|---|---|---|"]
    for c in r["checks"]:
        if len(r["checks"]) > 40 and c["pass_"] and r["group"] == "crash":
            continue   # per-crash-point detail is in the sweep tables above
        L.append(f"| {c['name']} | `{c['expected'][:70]}` | `{c['observed'][:70]}` | {'✔' if c['pass_'] else '✘'} |")
    L.append("")
open(dst, "w").write("\n".join(L))
print("wrote", dst, len("\n".join(L)), "bytes")
